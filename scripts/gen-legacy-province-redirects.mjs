#!/usr/bin/env node
// The sirinx.org knowledge site published /solar-carport-<province>/ URLs, while
// public-web publishes /solar-carport/<province>/. After moving .org onto the
// public-web bundle those indexed URLs would answer 404, so append an explicit
// 301 for every province that the build actually produced.
//
// Usage: node scripts/gen-legacy-province-redirects.mjs --dist=<built public dir>

import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const distArg = process.argv.find((a) => a.startsWith("--dist="))?.slice("--dist=".length);
if (!distArg) {
  console.error("refused: --dist=<built public dir> is required");
  process.exit(2);
}

const dist = resolve(REPO, distArg);
const redirectsPath = join(dist, "_redirects");
const provincesDir = join(dist, "solar-carport");
if (!existsSync(redirectsPath) || !existsSync(provincesDir)) {
  console.error(`refused: ${dist} does not look like a public-web build`);
  process.exit(2);
}

const slugs = readdirSync(provincesDir).filter((name) => statSync(join(provincesDir, name)).isDirectory()).sort();
const MARKER = "# ── Legacy sirinx.org province URLs (generated by scripts/gen-legacy-province-redirects.mjs) ──";
const base = readFileSync(redirectsPath, "utf8").split(MARKER)[0].replace(/\s+$/, "");
const block = [
  "",
  MARKER,
  "# Why: .org published /solar-carport-<slug>/ before it moved onto this bundle.",
  "# Removing these makes 77 indexed URLs answer 404 instead of 301.",
  ...slugs.map((slug) => `/solar-carport-${slug}/ /solar-carport/${slug}/ 301`),
  "",
].join("\n");

writeFileSync(redirectsPath, `${base}\n${block}`);
console.log(JSON.stringify({ dist: distArg, rules: slugs.length, first: slugs[0], last: slugs.at(-1) }, null, 2));
