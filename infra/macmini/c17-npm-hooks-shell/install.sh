#!/bin/sh
# C17 — make `hermes update`'s npm step survive a host-global `core.hooksPath`.
#
# Problem: ~/.gitconfig sets core.hooksPath (here: the codex hooks dir). Hermes'
# root `prepare` script runs `lefthook install`, which refuses any custom hooks
# path, so `npm ci` inside `hermes update` aborts. On 0.21.6 that failure killed
# the whole node-dependency step; on 0.22.5 the exit status is swallowed and the
# hooks silently stop being installed instead.
#
# Fix: npm runs lifecycle scripts through `script-shell`. Point that at a wrapper
# which gives git a *shim* global config — a byte-for-byte copy of ~/.gitconfig
# minus `core.hooksPath`. Identity, aliases, credential helpers and everything
# else stay intact; only the hooks path is cleared, so `lefthook install`
# succeeds and writes .git/hooks. Nothing inside the hermes checkout changes, so
# the fix survives `hermes update`; the user's real ~/.gitconfig is never edited.
#
# The shim is a copy, so re-run this script after editing ~/.gitconfig.
#
# Usage: install.sh [--dry-run|--apply]   (default: --dry-run)

set -eu

MODE=dry-run
for arg in "$@"; do
  case "$arg" in
    --dry-run) MODE=dry-run ;;
    --apply) MODE=apply ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    *) echo "unknown argument: $arg" >&2; exit 2 ;;
  esac
done

HOME_DIR=${HOME:?HOME is not set}
HERMES_DIR=${HERMES_DIR:-$HOME_DIR/.hermes}
GITCONFIG=$HOME_DIR/.gitconfig
SHIM=$HERMES_DIR/gitconfig-nohooks
BIN_DIR=$HERMES_DIR/bin
WRAPPER=$BIN_DIR/npm-script-shell
NPMRC=$HOME_DIR/.npmrc
STAMP=$(date +%Y%m%d-%H%M%S)

say() { printf '%s\n' "$*"; }

[ -f "$GITCONFIG" ] || { echo "no $GITCONFIG; nothing to shim" >&2; exit 1; }

# --- 1. render the shim (global config minus core.hooksPath) ----------------
tmp_shim=$(mktemp "${TMPDIR:-/tmp}/gitconfig-nohooks.XXXXXX")
trap 'rm -f "$tmp_shim"' EXIT
{
  echo "# GENERATED by infra/macmini/c17-npm-hooks-shell/install.sh on $STAMP."
  echo "# Copy of ~/.gitconfig with core.hooksPath removed so npm lifecycle"
  echo "# scripts (lefthook install in hermes' root prepare) can install hooks."
  echo "# Re-run that script after editing ~/.gitconfig."
  awk '
    /^[[:space:]]*\[/ { section = tolower($0) }
    section ~ /^[[:space:]]*\[core\]/ && tolower($0) ~ /^[[:space:]]*hookspath[[:space:]]*=/ { next }
    tolower($0) ~ /^[[:space:]]*hookspath[[:space:]]*=/ { next }
    { print }
  ' "$GITCONFIG"
} > "$tmp_shim"

dropped=$(grep -ci 'hookspath' "$GITCONFIG" || true)
if [ "$dropped" -eq 0 ]; then
  say "note: $GITCONFIG sets no core.hooksPath — the shim is unnecessary on this host."
fi
if grep -qi '^[[:space:]]*\[include' "$GITCONFIG"; then
  say "warning: $GITCONFIG uses [include]/[includeIf]; a hooksPath set by an included file is not stripped."
fi

# --- 2. describe the wrapper -------------------------------------------------
wrapper_body='#!/bin/sh
# C17 npm lifecycle shell: give git a global config without core.hooksPath so
# `lefthook install` (root `prepare`) succeeds during `hermes update`/`npm ci`.
# Identity, aliases and credential helpers come from the shim, not /dev/null.
shim=${HERMES_GITCONFIG_NOHOOKS:-__SHIM__}
if [ -f "$shim" ]; then
  GIT_CONFIG_GLOBAL=$shim
  export GIT_CONFIG_GLOBAL
fi
exec /bin/sh "$@"'

# --- 3. plan/apply -----------------------------------------------------------
say "mode:      $MODE"
say "shim:      $SHIM ($(grep -c '' "$tmp_shim") lines, hooksPath stripped)"
say "wrapper:   $WRAPPER"
say "npmrc:     $NPMRC  <- script-shell=$WRAPPER"

if [ "$MODE" = dry-run ]; then
  say ""
  say "dry-run: nothing written. Re-run with --apply."
  exit 0
fi

mkdir -p "$BIN_DIR"
cp "$tmp_shim" "$SHIM"
chmod 600 "$SHIM"
printf '%s\n' "$wrapper_body" | sed "s|__SHIM__|$SHIM|" > "$WRAPPER"
chmod 755 "$WRAPPER"

if [ -f "$NPMRC" ] && grep -q '^[[:space:]]*script-shell[[:space:]]*=' "$NPMRC"; then
  current=$(sed -n 's/^[[:space:]]*script-shell[[:space:]]*=[[:space:]]*//p' "$NPMRC" | tail -1)
  if [ "$current" = "$WRAPPER" ]; then
    say "npmrc: script-shell already set to this wrapper"
  else
    echo "refusing: $NPMRC already sets script-shell=$current" >&2
    exit 3
  fi
else
  if [ -f "$NPMRC" ]; then
    cp -p "$NPMRC" "$NPMRC.bak-$STAMP"
    say "npmrc: backed up to $NPMRC.bak-$STAMP"
  fi
  printf 'script-shell=%s\n' "$WRAPPER" >> "$NPMRC"
  say "npmrc: script-shell appended"
fi

# --- 4. verify ---------------------------------------------------------------
fail=0
if GIT_CONFIG_GLOBAL=$SHIM git config --get core.hooksPath >/dev/null 2>&1; then
  echo "FAIL: shim still reports core.hooksPath" >&2; fail=1
else
  say "verify: shim exposes no core.hooksPath"
fi
real_ident=$(git config --get user.email 2>/dev/null || true)
shim_ident=$(GIT_CONFIG_GLOBAL=$SHIM git config --get user.email 2>/dev/null || true)
if [ "$real_ident" = "$shim_ident" ]; then
  say "verify: identity preserved (user.email unchanged)"
else
  echo "FAIL: shim changed user.email ($real_ident -> $shim_ident)" >&2; fail=1
fi
wrapped_ident=$(GIT_CONFIG_GLOBAL=$SHIM "$WRAPPER" -c 'git config --get user.email' 2>/dev/null || true)
if [ "$wrapped_ident" = "$real_ident" ]; then
  say "verify: lifecycle shell keeps identity"
else
  echo "FAIL: lifecycle shell lost identity" >&2; fail=1
fi
[ "$fail" -eq 0 ] || exit 4

say ""
say "applied. Next: prove it in the checkout —"
say "  cd ~/.hermes/hermes-agent"
say "  node scripts/build/node-deps.mjs --source \"\$PWD\" --workspace apps/desktop --workspace ui-tui --workspace web"
say "  # expect: 'sync hooks: pre-commit' and no 'Custom hooks paths' refusal"
